export const yearText = (y) =>
  !y ? '' : y <= 4 ? tr(`${y} კურსი`, `Year ${y}`) : y <= 6 ? tr(`მაგისტრატურა, ${y - 4} კურსი`, `Master's, year ${y - 4}`) : tr('დოქტორანტურა', 'PhD')

export const studyLine = (p) => [p.university, p.faculty, yearText(p.year)].filter(Boolean).join(' · ')

